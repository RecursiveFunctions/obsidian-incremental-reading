/**
 * SM-18 element browser: the knowledge-tree navigation surface.
 *
 * Composed from the already-ported `parseContents` and `parseElementInfo`
 * (`src/sm18-format-read.ts`, landed by sm18-re #36 + #39) — this module adds
 * no new byte-level decoding. The conformance fixture is
 * `test/fixtures/sm18-port-element-browser.json`, a byte-exact mirror of
 * `sm18-re:tests/fixtures/port-element-browser.json` generated from the sample
 * collection "ABC of SuperMemo 18"; the contract test is
 * `test/sm18-port-element-browser.test.ts`.
 *
 * This is v1 of the `element_browser` surface (sm18-re gitlab #56). It is the
 * last input surface the ported scheduler (#28) and priority queue (#32) need:
 * without a way to pick an element out of a real collection's tree, neither
 * can be exercised against one.
 *
 * ## Why the navigation names live here and not in `parseContents`
 *
 * `ContentsRecord` in `src/sm18-format-read.ts` names its ten members after
 * their byte offsets — `unknown_0x00` … `unknown_0x21`. That was deliberate:
 * when the contents decoder was ported, the campaign repository had not yet
 * defended what the fields mean, and naming them `parent` / `child` /
 * `sibling` would have smuggled an undefended semantic claim into a module
 * that reads like evidence.
 *
 * sm18-re #44 (`contents.dat` semantics, round 2) earned those names. The
 * mapping below is the one place in the port where the semantic claim enters,
 * and every entry in it is quoted from `sm18-re:docs/findings/contents.md`:
 *
 * | offset | name                | how it was earned                                                    |
 * |--------|---------------------|----------------------------------------------------------------------|
 * | `0x00` | `slot_removed`      | `Contents_UnlinkNodeFromTree` (`0x93273c`) tests this byte, raises "Deleting knowledge tree element that has already been deleted" when set, then sets it to 1. Cross-file: all 1,199 records with it set are `element_status == 3` (`Deleted`). |
 * | `0x01` | `parent_id`         | `Contents_FormatTreeNodeDiagnostics` (`0x853448`) prints these five, in this order, read out of a `contents.dat` record buffer at exactly these offsets: `(Structure: Parent=`, `FirstChild=`, `LastChild=`, `PrevSibling=`, `NextSibling=`. |
 * | `0x05` | `first_child_id`    | as above |
 * | `0x09` | `last_child_id`     | as above |
 * | `0x0d` | `prev_sibling_id`   | as above |
 * | `0x11` | `next_sibling_id`   | as above |
 * | `0x15` | `descendant_count`  | accessor `0x933644` seeks `n - 1`, reads one record at `EBP - 0x41` and returns the dword at `EBP - 0x2c`; `0x41 - 0x2c == 0x15`. Equals the subtree size, exclusive of the node, on 31,000+ records with zero mismatches. |
 * | `0x19` | `child_count`       | equals `|{j live : parent_id(j) == i}|` and the length of the `first_child_id`/`next_sibling_id` walk, zero mismatches across all six files. |
 *
 * The two remaining offsets, `0x1d` and `0x21`, keep their `unknown_*` labels.
 * They are zero in every record of every known collection and they are not
 * navigation fields, so the walk never consults them; they are carried through
 * the projection only so a caller sees the whole record. Renaming them is a
 * `contents` round-3 concern, not this lane's.
 *
 * Note that renaming the members of `ContentsRecord` itself was not an option:
 * `test/sm18-port-format-read-contents.test.ts` pins the offset-label keys
 * through its own fixture, and that fixture is generated by a different
 * sm18-re exporter. The relabelling therefore happens on the way into this
 * module's projection.
 *
 * ## Element ids are 1-based
 *
 * Every id stored in a `contents.dat` record is an *element number*, and
 * element number `n` lives at file offset `(n - 1) * 37`. The executable does
 * the same subtraction: `Contents_ReadNodeRecord` (`0x9315a8`) seeks with
 * `n - 1`, and `Contents_ReadSubtreeElementCount` (`0x933644`) returns 0 for
 * element number 0. Id 0 is therefore not an element — it is the null
 * terminator of every link field, which is what makes the sibling chains
 * null-terminated at both ends and the root identifiable by `parent_id == 0`.
 *
 * The same element numbers index `ElementInfo.dat`, which is how a node's
 * `element_type` / `element_status` are joined onto its tree record: contents
 * record index `i` and ElementInfo record index `i` are both element `i + 1`.
 * No search, no key — the join is positional.
 *
 * ## Removed slots
 *
 * `slot_removed != 0` means the slot has been unlinked from the tree, not that
 * the record was wiped. `Contents_UnlinkNodeFromTree` writes the flag back
 * into the record it just read and never clears `parent_id`,
 * `prev_sibling_id` or `next_sibling_id`, so a dead slot keeps **stale** link
 * values. In the sample collection, id 12 still claims `parent_id 7`,
 * `prev_sibling_id 11` and `next_sibling_id 8` while being `Deleted`.
 *
 * Two consequences the policy below turns on:
 *
 * 1. Dead slots are reachable through `node(id)` — they are real records and
 *    hiding them would make the browser disagree with the file — but they are
 *    excluded from `rootIds()` and never appear in `preorder()`. A dead slot
 *    whose stale `parent_id` happens to be 0 is reusable storage, not a tree
 *    entry.
 * 2. The walk itself needs no `slot_removed` filter. `docs/findings/contents.md`
 *    establishes that no *live* record's `parent_id`, `first_child_id`,
 *    `last_child_id`, `prev_sibling_id` or `next_sibling_id` ever points at a
 *    removed slot, with zero violations across 31,000+ records. The live
 *    chains simply do not mention the dead, so descending them cannot reach
 *    one. Filtering inside the walk as well would be belt-and-braces that
 *    silently masks a corrupt collection instead of reporting it; the
 *    reachability invariant asserted at open time reports it.
 */

import {
  ELEMENT_STATUSES,
  ELEMENT_TYPES,
  parseContents,
  parseElementInfo,
  type ContentsRecord,
  type ElementInfoRecord,
} from "./sm18-format-read";

/**
 * One element as the browser projects it: its 1-based element number, all ten
 * `contents.dat` members under the names sm18-re #44 earned for them, and the
 * two `ElementInfo.dat` enums with their labels.
 *
 * Deliberately no title. Resolving one means walking the
 * `.lst` → `.mem`/`.ptr`/`.rtx` registry chain, which is a product-level
 * follow-up; the structural fields are what a scheduler needs to pick an
 * element.
 */
export interface NodeProjection {
  /** 1-based element number. Element `n` is contents record index `n - 1`. */
  id: number;
  /** `0x00`: 0 = live tree node, 1 = slot unlinked from the tree. */
  slot_removed: number;
  /** `0x01`: owning element, or 0 for a root. Stale on a removed slot. */
  parent_id: number;
  /** `0x05`: head of the child chain, or 0 for a leaf. */
  first_child_id: number;
  /** `0x09`: tail of the child chain, or 0 for a leaf. */
  last_child_id: number;
  /** `0x0d`: previous sibling, 0 at the head of the chain. */
  prev_sibling_id: number;
  /** `0x11`: next sibling, 0 at the tail of the chain. */
  next_sibling_id: number;
  /** `0x15`: subtree size, excluding this node. */
  descendant_count: number;
  /** `0x19`: number of direct children. */
  child_count: number;
  /** `0x1d`: undefended. Zero in every known collection; never walked. */
  unknown_0x1d: number;
  /** `0x21`: undefended. Zero in every known collection; never walked. */
  unknown_0x21: number;
  /** `ElementInfo.dat` `0x00`. */
  element_type: number;
  /** `ElementInfo.dat` `0x01`. */
  element_status: number;
  /** `ELEMENT_TYPES[element_type]`, or `""` for a value outside the enum. */
  element_type_name: string;
  /** `ELEMENT_STATUSES[element_status]`, or `""` outside the enum. */
  element_status_name: string;
}

/** Read-only navigation over one collection's knowledge tree. */
export interface ElementBrowser {
  /**
   * Every live id with `parent_id == 0`, in file order. A well-formed
   * collection has exactly one; the signature stays plural because nothing in
   * the format enforces that, and a browser that assumed it would throw on a
   * collection SuperMemo itself opens.
   */
  rootIds(): number[];
  /**
   * The projection for one element number, live or removed. Throws for any id
   * that is not a record in this collection — including 0, which is the link
   * fields' null terminator and not an element.
   */
  node(id: number): NodeProjection;
  /**
   * Depth-first preorder over the live tree: each root, then its subtree via
   * `first_child_id` and `next_sibling_id`. Covers every live record exactly
   * once and no removed slot.
   */
  preorder(): number[];
}

/** The ten `NodeProjection` members that come straight off a contents record. */
type ContentsDerivedKey = Exclude<
  keyof NodeProjection,
  | "id"
  | "element_type"
  | "element_status"
  | "element_type_name"
  | "element_status_name"
>;

/**
 * `ContentsRecord`'s offset-label members paired with the ten navigation names
 * sm18-re #44 earned for them. Keeping the pairing as data rather than ten
 * assignments means this table is the only place the relabelling happens, and
 * because both sides are keyed types, a rename on either side — a future
 * `ContentsRecord` that drops `unknown_0x00`, or a `NodeProjection` member
 * this table forgets — is a build error rather than a silently mislabelled
 * field.
 */
const NAVIGATION_FIELDS: ReadonlyArray<
  readonly [keyof ContentsRecord, ContentsDerivedKey]
> = [
  ["unknown_0x00", "slot_removed"],
  ["unknown_0x01", "parent_id"],
  ["unknown_0x05", "first_child_id"],
  ["unknown_0x09", "last_child_id"],
  ["unknown_0x0d", "prev_sibling_id"],
  ["unknown_0x11", "next_sibling_id"],
  ["unknown_0x15", "descendant_count"],
  ["unknown_0x19", "child_count"],
  ["unknown_0x1d", "unknown_0x1d"],
  ["unknown_0x21", "unknown_0x21"],
];

/** Element number of contents record index `i`. Mirrors `contents.record_id`. */
export function elementId(recordIndex: number): number {
  return recordIndex + 1;
}

/** Relabel one contents record and join its ElementInfo row onto it. */
function project(
  recordIndex: number,
  contentsRecord: ContentsRecord,
  elementInfoRecord: ElementInfoRecord,
): NodeProjection {
  const navigation = {} as Record<ContentsDerivedKey, number>;
  for (const [source, target] of NAVIGATION_FIELDS) {
    navigation[target] = contentsRecord[source];
  }
  const elementType = elementInfoRecord.element_type;
  const elementStatus = elementInfoRecord.element_status;
  return {
    id: elementId(recordIndex),
    ...navigation,
    element_type: elementType,
    element_status: elementStatus,
    element_type_name: ELEMENT_TYPES[elementType] ?? "",
    element_status_name: ELEMENT_STATUSES[elementStatus] ?? "",
  };
}

/**
 * The child chain under `id`, head to tail, via `first_child_id` then
 * `next_sibling_id`.
 *
 * A link to an id this collection does not hold throws rather than being
 * skipped: the whole value of reading the chains is that they are the
 * executable's own structure, and a chain that leaves the file is a corrupt
 * collection, not a shorter chain. The step counter is a second guard — a
 * chain that cycles among ids that *do* exist would otherwise spin forever,
 * and no sibling chain can be longer than the record count.
 */
function childChain(
  nodesById: Map<number, NodeProjection>,
  id: number,
): number[] {
  const children: number[] = [];
  let cursor = nodesById.get(id)!.first_child_id;
  while (cursor !== 0) {
    const child = nodesById.get(cursor);
    if (child === undefined) {
      throw new Error(
        `contents.dat child chain under element ${id} references missing id ${cursor}`,
      );
    }
    children.push(cursor);
    if (children.length > nodesById.size) {
      throw new Error(
        `contents.dat sibling chain under element ${id} exceeds the record count`,
      );
    }
    cursor = child.next_sibling_id;
  }
  return children;
}

/**
 * Preorder over the live tree, iterative so a deep collection cannot overflow
 * the stack (`Cyber` is 16,880 live records).
 *
 * The `visited` set is the cycle guard: `contents.dat` holds explicit ids, so
 * a corrupt file can describe a loop, and a second visit means the structure
 * is not a tree. Bailing is the only honest response — a browser that
 * deduplicated instead would hand a caller a silently truncated tree.
 */
function preorderWalk(
  nodesById: Map<number, NodeProjection>,
  rootIds: readonly number[],
): number[] {
  const order: number[] = [];
  const visited = new Set<number>();
  const stack: number[] = [...rootIds].reverse();
  while (stack.length > 0) {
    const id = stack.pop()!;
    if (visited.has(id)) {
      throw new Error(`contents.dat tree has a cycle at element ${id}`);
    }
    visited.add(id);
    order.push(id);
    const children = childChain(nodesById, id);
    for (let i = children.length - 1; i >= 0; i -= 1) {
      stack.push(children[i]);
    }
  }
  return order;
}

/**
 * Open a collection's knowledge tree for read-only navigation.
 *
 * `contents` is `info/contents.dat`, `elementInfo` is `info/ElementInfo.dat`.
 * Both are decoded by the existing format-read parsers, so a length that does
 * not tile into whole records throws there, before anything here runs.
 *
 * The whole projection is built eagerly. Both files are small enough for that
 * (`Cyber`, the largest known collection, is 18,076 records ≈ 670 KB of
 * `contents.dat`), and it is what lets the two structural invariants below be
 * checked at open time rather than surfacing as a wrong answer three calls
 * later.
 */
export function openElementBrowser(opts: {
  contents: Uint8Array;
  elementInfo: Uint8Array;
}): ElementBrowser {
  const contentsRecords = parseContents(opts.contents);
  const elementInfoRecords = parseElementInfo(opts.elementInfo);

  // SM-18 has its own error path for this pair disagreeing — the string
  // "Different number of elements in Contents.dat and ElementInfo.dat" at
  // `0x9056e8` — so refusing here mirrors the executable rather than inventing
  // a rule. It is a real v1 limitation, not a theoretical one: `Cyber` holds
  // 18,076 contents records against 17,987 ElementInfo rows, and
  // `docs/findings/contents.md` reads that overhang as a tolerated state of
  // the pair. Projecting the overhang needs a defended account of what an
  // ElementInfo-less contents slot is, which no sm18-re lane has produced; a
  // join policy guessed here would be exactly the back-derived semantics this
  // surface was re-filed to avoid.
  if (contentsRecords.length !== elementInfoRecords.length) {
    throw new Error(
      "different number of elements in contents.dat and ElementInfo.dat: " +
        `${contentsRecords.length} vs ${elementInfoRecords.length}`,
    );
  }

  const nodes: NodeProjection[] = [];
  const nodesById = new Map<number, NodeProjection>();
  for (let i = 0; i < contentsRecords.length; i += 1) {
    const node = project(i, contentsRecords[i], elementInfoRecords[i]);
    nodes.push(node);
    nodesById.set(node.id, node);
  }

  const rootIds = nodes
    .filter((n) => n.parent_id === 0 && n.slot_removed === 0)
    .map((n) => n.id);
  const order = preorderWalk(nodesById, rootIds);

  // Reachability. `descendant_count` on the root plus one equals the live
  // record count in every known collection, which is the arithmetic #44 used
  // to earn `slot_removed` in the first place: the records the root can reach
  // are precisely the records with the flag clear. A live record the walk
  // never visits means the file disagrees with that, and a browser whose
  // `preorder()` silently omitted an element would be worse than one that
  // refuses to open.
  const liveCount = nodes.filter((n) => n.slot_removed === 0).length;
  if (order.length !== liveCount) {
    throw new Error(
      "contents.dat preorder walk did not cover every live element: " +
        `${order.length} visited vs ${liveCount} live ` +
        `(${nodes.length - liveCount} removed)`,
    );
  }

  for (const node of nodes) {
    Object.freeze(node);
  }

  return {
    rootIds: () => [...rootIds],
    node: (id: number) => {
      const node = nodesById.get(id);
      if (node === undefined) {
        throw new Error(
          `unknown element id ${id}: this collection holds elements 1..${nodes.length}`,
        );
      }
      return node;
    },
    preorder: () => [...order],
  };
}
