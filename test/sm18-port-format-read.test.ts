/**
 * Golden contract for the SM-18 format-read port, v1 (sm18-re gitlab #36).
 *
 * v1 scope: `info/ElementInfo.dat` and `info/compon.dat` decoders. The
 * other in-scope groups from the campaign issue (`info/contents.dat`, the
 * registry chain, `info/RepetitionHistory.dat`, `info/*.sub` + `subsets/*.sub`,
 * `collection.kno`) each ship under their own follow-up lane with their own
 * fixture file and harness. The `format_read` surface in
 * `sm18-re:docs/port-surface.json` only flips when every follow-up has
 * landed; a green run here is proof of v1 landing, not of the whole surface.
 *
 * The fixture `test/fixtures/sm18-port-format-read.json` is a mirror of
 * `sm18-re:tests/fixtures/port-format-read.json`, regenerated by
 * `sm18-re:scripts/export-port-format-read-fixture.py` on the sample
 * collection "ABC of SuperMemo 18". The lane re-copies the mirror on every
 * fixture change so sm18-re's gate catches drift on either side.
 *
 * This file is brief-writer owned. The lane implements
 * `src/sm18-format-read.ts` with two parsers:
 *
 *   - `parseElementInfo(buf: Uint8Array): ElementInfoRecord[]`
 *   - `parseCompon(buf: Uint8Array): ComponRecord[]`
 *
 * The record shapes are declared below. ElementInfo records expose every
 * field the Python reference exposes; the four 6-byte extended-precision
 * fields (`a_factor`, `u_factor`, `difficulty`, `ordinal`) stay as byte
 * arrays so the port is held to a bytes-in / bytes-out contract rather than
 * a floating-point decode the fixture would not pin.
 *
 * Each file in the fixture carries its raw bytes inline as `bytes_b64`. The
 * harness decodes those bytes and feeds them to the parser so `npm test`
 * stays self-contained; no `artifacts/` tree or symlink is needed in the
 * port target.
 */

import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { join } from "node:path";

const FIXTURE_PATH = join(__dirname, "fixtures", "sm18-port-format-read.json");
const MODULE_SPEC = ["..", "src", "sm18-format-read.ts"].join("/");

interface HexBlob {
  hex: string;
}

interface ElementInfoRecord {
  element_type: number;
  element_status: number;
  text_registry_member: number;
  compon_offset: number;
  compon_body_length: number;
  repetition_count: number;
  lapse_count: number;
  interval_days: number;
  last_repetition_day: number;
  last_repetition_date: number;
  a_factor: HexBlob;
  u_factor: HexBlob;
  last_repetition_row: number;
  reference_registry_member: number;
  forgetting_index: number;
  total_postpone_count: number;
  recent_postpone_count: number;
  comment_registry_member: number;
  template_registry_member: number;
  concept_group_member: number;
  concept_definition_member: number;
  reserved: number;
  extraction_date: number;
  legacy: number;
  legacy_element_number: number;
  source_article: number;
  difficulty: HexBlob;
  ordinal: HexBlob;
  first_grade: number;
  first_repetition_day: number;
}

interface ComponComponent {
  component_type: number;
  buffer_size: number;
}

interface ComponRecord {
  element_number: number;
  component_count: number;
  element_param_size: number;
  components: ComponComponent[];
}

interface FixtureFile {
  path: string;
  byte_length: number;
  bytes_b64: string;
  record_count: number;
  records: ElementInfoRecord[] | ComponRecord[];
}

interface Fixture {
  schema: number;
  collection: string;
  v1_scope: string[];
  files: FixtureFile[];
}

interface PortModule {
  parseElementInfo: (bytes: Uint8Array) => ElementInfoRecord[];
  parseCompon: (bytes: Uint8Array) => ComponRecord[];
}

async function loadPort(): Promise<PortModule | null> {
  try {
    const mod = await import(MODULE_SPEC);
    if (
      typeof mod?.parseElementInfo !== "function" ||
      typeof mod?.parseCompon !== "function"
    ) {
      return null;
    }
    return mod as PortModule;
  } catch {
    return null;
  }
}

function decodeBase64(encoded: string): Uint8Array {
  return new Uint8Array(Buffer.from(encoded, "base64"));
}

const fixture: Fixture = JSON.parse(readFileSync(FIXTURE_PATH, "utf8"));

test("fixture declares the v1 scope and non-empty files", () => {
  assert.equal(fixture.schema, 1);
  assert.deepEqual(fixture.v1_scope, ["element_info", "compon"]);
  assert.equal(fixture.files.length, 2);
  for (const file of fixture.files) {
    assert.ok(file.record_count > 0, `${file.path} has records`);
    assert.ok(file.byte_length > 0, `${file.path} has bytes`);
  }
});

test("src/sm18-format-read.ts exports parseElementInfo and parseCompon", async (t) => {
  const port = await loadPort();
  if (port === null) {
    t.skip("src/sm18-format-read.ts not implemented yet");
    return;
  }
  assert.equal(typeof port.parseElementInfo, "function");
  assert.equal(typeof port.parseCompon, "function");
});

for (const file of fixture.files) {
  test(`format-read: ${file.path} parses to ${file.record_count} records`, async (t) => {
    const port = await loadPort();
    if (port === null) {
      t.skip("src/sm18-format-read.ts not implemented yet");
      return;
    }
    const bytes = decodeBase64(file.bytes_b64);
    assert.equal(
      bytes.byteLength,
      file.byte_length,
      `byte count for ${file.path}`,
    );
    const parsed: unknown[] = file.path.endsWith("ElementInfo.dat")
      ? port.parseElementInfo(bytes)
      : port.parseCompon(bytes);
    assert.equal(
      parsed.length,
      file.record_count,
      `record count for ${file.path}`,
    );
    for (let i = 0; i < file.record_count; i += 1) {
      assert.deepEqual(
        parsed[i],
        file.records[i],
        `record ${i} of ${file.path} must match the fixture projection`,
      );
    }
  });
}
