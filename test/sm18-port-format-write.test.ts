/**
 * Golden contract for the SM-18 format-write port, v1 (sm18-re gitlab #38).
 *
 * v1 scope: `info/ElementInfo.dat` and `info/compon.dat` encoders. The
 * other in-scope groups from the campaign issue (`info/contents.dat`, the
 * registry chain, `info/RepetitionHistory.dat`, `info/*.sub` + `subsets/*.sub`,
 * `collection.kno`, the alg17 grids) each ship under their own follow-up lane
 * with their own fixture file and harness. The `format_write` surface in
 * `sm18-re:docs/port-surface.json` only flips when every follow-up has
 * landed; a green run here is proof of v1 landing, not of the whole surface.
 *
 * The fixture `test/fixtures/sm18-port-format-write.json` is a mirror of
 * `sm18-re:tests/fixtures/port-format-write.json`, regenerated by
 * `sm18-re:scripts/export-port-format-write-fixture.py` on the sample
 * collection "ABC of SuperMemo 18". The lane re-copies the mirror on every
 * fixture change so sm18-re's gate catches drift on either side.
 *
 * This file is brief-writer owned. The lane implements
 * `src/sm18-format-write.ts` with two encoders:
 *
 *   - `writeElementInfo(header: Uint8Array, records: ElementInfoRecord[]): Uint8Array`
 *   - `writeCompon(header: Uint8Array, records: ComponRawRecord[]): Uint8Array`
 *
 * ElementInfo takes the same record shape the format-read fixture pins (the
 * four Real48 fields `a_factor`, `u_factor`, `difficulty`, `ordinal` are
 * `{hex: string}`; every other field is `number`), repacks each record into
 * the fixed-width record block declared by `smfmt.element_info.FIELDS`, and
 * prepends the (empty) header.
 *
 * Compon takes a per-record `{raw_b64}` carrier and concatenates the bytes.
 * The Python writer's declared contract is "rebuild the file byte for byte
 * from the records parse returned"; the v1 TS writer honours the same
 * contract. A later follow-up lane can bring the typed record shape in once
 * `smfmt.compon.encode_record` is settled on this side; the brief does not
 * widen v1 beyond byte round-trip because `_raw` is what format-read drops.
 *
 * Each file in the fixture carries the stored bytes inline as
 * `expected_bytes_b64`. The harness feeds the record arrays into the TS
 * encoders and asserts the output byte sequence equals `expected_bytes_b64`.
 */

import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { join } from "node:path";

const FIXTURE_PATH = join(__dirname, "fixtures", "sm18-port-format-write.json");
const MODULE_SPEC = ["..", "src", "sm18-format-write.ts"].join("/");

interface HexBlob {
  hex: string;
}

interface ElementInfoRecord {
  element_type: number;
  element_status: number;
  text_registry_member: number;
  compon_offset: number;
  compon_body_length: number;
  repetition_count: number;
  lapse_count: number;
  interval_days: number;
  last_repetition_day: number;
  last_repetition_date: number;
  a_factor: HexBlob;
  u_factor: HexBlob;
  last_repetition_row: number;
  reference_registry_member: number;
  forgetting_index: number;
  total_postpone_count: number;
  recent_postpone_count: number;
  comment_registry_member: number;
  template_registry_member: number;
  concept_group_member: number;
  concept_definition_member: number;
  reserved: number;
  extraction_date: number;
  legacy: number;
  legacy_element_number: number;
  source_article: number;
  difficulty: HexBlob;
  ordinal: HexBlob;
  first_grade: number;
  first_repetition_day: number;
}

interface ComponRawRecord {
  raw_b64: string;
}

interface FixtureFile {
  path: string;
  byte_length: number;
  header_b64: string;
  record_count: number;
  records: ElementInfoRecord[] | ComponRawRecord[];
  expected_bytes_b64: string;
}

interface Fixture {
  schema: number;
  collection: string;
  v1_scope: string[];
  files: FixtureFile[];
}

interface PortModule {
  writeElementInfo: (
    header: Uint8Array,
    records: ElementInfoRecord[],
  ) => Uint8Array;
  writeCompon: (
    header: Uint8Array,
    records: ComponRawRecord[],
  ) => Uint8Array;
}

async function loadPort(): Promise<PortModule | null> {
  try {
    const mod = await import(MODULE_SPEC);
    if (
      typeof mod?.writeElementInfo !== "function" ||
      typeof mod?.writeCompon !== "function"
    ) {
      return null;
    }
    return mod as PortModule;
  } catch {
    return null;
  }
}

function decodeBase64(encoded: string): Uint8Array {
  return new Uint8Array(Buffer.from(encoded, "base64"));
}

function bytesEqual(a: Uint8Array, b: Uint8Array): boolean {
  if (a.byteLength !== b.byteLength) return false;
  for (let i = 0; i < a.byteLength; i += 1) {
    if (a[i] !== b[i]) return false;
  }
  return true;
}

const fixture: Fixture = JSON.parse(readFileSync(FIXTURE_PATH, "utf8"));

test("fixture declares the v1 scope and non-empty files", () => {
  assert.equal(fixture.schema, 1);
  assert.deepEqual(fixture.v1_scope, ["element_info", "compon"]);
  assert.equal(fixture.files.length, 2);
  for (const file of fixture.files) {
    assert.ok(file.record_count > 0, `${file.path} has records`);
    assert.ok(file.byte_length > 0, `${file.path} has bytes`);
    assert.ok(
      typeof file.expected_bytes_b64 === "string" &&
        file.expected_bytes_b64.length > 0,
      `${file.path} carries expected bytes`,
    );
  }
});

test("src/sm18-format-write.ts exports writeElementInfo and writeCompon", async (t) => {
  const port = await loadPort();
  if (port === null) {
    t.skip("src/sm18-format-write.ts not implemented yet");
    return;
  }
  assert.equal(typeof port.writeElementInfo, "function");
  assert.equal(typeof port.writeCompon, "function");
});

for (const file of fixture.files) {
  test(`format-write: ${file.path} rebuilds ${file.byte_length} bytes`, async (t) => {
    const port = await loadPort();
    if (port === null) {
      t.skip("src/sm18-format-write.ts not implemented yet");
      return;
    }
    const header = decodeBase64(file.header_b64);
    const expected = decodeBase64(file.expected_bytes_b64);
    assert.equal(
      expected.byteLength,
      file.byte_length,
      `expected byte count for ${file.path}`,
    );
    const produced = file.path.endsWith("ElementInfo.dat")
      ? port.writeElementInfo(header, file.records as ElementInfoRecord[])
      : port.writeCompon(header, file.records as ComponRawRecord[]);
    assert.ok(
      bytesEqual(produced, expected),
      `${file.path} must round-trip byte for byte (` +
        `got ${produced.byteLength} bytes, expected ${expected.byteLength})`,
    );
  });
}
