/**
 * Golden contract for the SM-18 format-read port follow-up on the registry
 * chain (sm18-re gitlab #40).
 *
 * Follow-up to #36. v1 landed `parseElementInfo` + `parseCompon`; this gate
 * adds `parseRegistryMem`, `parseRegistryPtr`, `parseRegistryLst`,
 * `parseRegistryRtx` and the integrating `resolveRegistry`. The
 * `format_read` surface in `sm18-re:docs/port-surface.json` only flips when
 * every follow-up has landed; a green run here is proof of this group's
 * landing, not of the whole surface.
 *
 * The fixture `test/fixtures/sm18-port-format-read-registry.json` is a
 * mirror of `sm18-re:tests/fixtures/port-format-read-registry.json`,
 * regenerated by `sm18-re:scripts/export-port-format-read-registry-fixture.py`
 * on the sample collection "ABC of SuperMemo 18". The lane re-copies the
 * mirror on every fixture change so sm18-re's gate catches drift on either
 * side.
 *
 * This file is brief-writer owned. The lane adds, additively, to
 * `src/sm18-format-read.ts`:
 *
 *   parseRegistryMem(bytes: Uint8Array): RegistryMemRecord[]
 *   parseRegistryPtr(bytes: Uint8Array): number[]
 *   parseRegistryLst(bytes: Uint8Array): RegistryLstRecord[]
 *   parseRegistryRtx(bytes: Uint8Array): RtxSpan[]
 *   resolveRegistry(parts: { mem, ptr, rtx }): RegistrySpan[]
 *
 * ## Privacy — read before touching the fixture
 *
 * `.rtx` is the file that holds user prose in SuperMemo (chiefly
 * `text.rtx`). The fixture **does not** inline raw `.rtx` bytes. The
 * exporter replaces every byte that is not a null terminator or a `<IB>`
 * trailer with `0x58` ('X'), so the structural layout — record
 * boundaries, member numbers, active flags, span offsets, span lengths —
 * survives verbatim and the port's parsers run against the redacted
 * stream to produce geometrically identical records. Per-member
 * `payload_sha256` is pinned for audit; the harness does **not** check it
 * (there is no way to recover it from redacted bytes), so a lane author
 * must not try to.
 *
 * `.mem`, `.ptr` and `.lst` are numeric index files. They inline whole
 * via base64. No decoded payload is ever printed from this harness.
 *
 * ## Non-wiring
 *
 * - `resolveRegistry` composes `.mem` + `.ptr` + `.rtx` into
 *   `member -> span`. It does **not** take paths; the port owns no
 *   filesystem walk.
 * - The port must reproduce `ExternalChain` (payload addressed outside
 *   the generic chain) as an error, not swallow it. The ABC fixture does
 *   not exercise this case, so a lane-authored unit test must cover it
 *   with a synthetic input.
 */

import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { join } from "node:path";

const FIXTURE_PATH = join(
  __dirname,
  "fixtures",
  "sm18-port-format-read-registry.json",
);
const MODULE_SPEC = ["..", "src", "sm18-format-read.ts"].join("/");

interface HexBlob {
  hex: string;
}

interface RegistryMemRecord {
  unknown_0x00: number;
  unknown_0x04: number;
  unknown_0x08: number;
  unknown_0x0a: number;
  unknown_0x0c: number;
  unknown_0x10: HexBlob;
  unknown_0x18: HexBlob;
}

interface RegistryLstRecord {
  unknown_0x00: number;
  unknown_0x04: number;
}

interface RtxMember {
  member_number: number;
  span_offset: number;
  span_length: number;
  trailer_active: number;
  payload_sha256: string;
}

interface MemFile {
  path: string;
  byte_length: number;
  bytes_b64: string;
  record_count: number;
  records: RegistryMemRecord[];
}

interface PtrFile {
  path: string;
  byte_length: number;
  bytes_b64: string;
  record_count: number;
  member_numbers: number[];
}

interface LstFile {
  path: string;
  byte_length: number;
  bytes_b64: string;
  record_count: number;
  records: RegistryLstRecord[];
}

interface RtxFile {
  path: string;
  byte_length: number;
  redacted_bytes_b64: string;
  redacted_sha256: string;
  live_member_count: number;
  members: RtxMember[];
}

interface KindEntry {
  kind: string;
  mem: MemFile;
  ptr: PtrFile;
  lst: LstFile;
  rtx: RtxFile;
}

interface Fixture {
  schema: number;
  collection: string;
  scope: string[];
  member_stride: number;
  ptr_stride: number;
  lst_stride: number;
  trailer_struct: string;
  span_struct: string;
  span_offset_in_member: number;
  trailer_size: number;
  kinds: KindEntry[];
}

interface RtxSpan {
  member_number: number;
  active: number;
  span_offset: number;
  span_length: number;
  payload?: Uint8Array;
}

interface ResolvedSpan {
  member_number: number;
  span_offset: number;
  span_length: number;
}

interface PortModule {
  parseRegistryMem: (bytes: Uint8Array) => RegistryMemRecord[];
  parseRegistryPtr: (bytes: Uint8Array) => number[];
  parseRegistryLst: (bytes: Uint8Array) => RegistryLstRecord[];
  parseRegistryRtx: (bytes: Uint8Array) => RtxSpan[];
  resolveRegistry: (parts: {
    mem: Uint8Array;
    ptr: Uint8Array;
    rtx: Uint8Array;
  }) => ResolvedSpan[] | Map<number, ResolvedSpan>;
}

async function loadPort(): Promise<PortModule | null> {
  try {
    const mod = await import(MODULE_SPEC);
    const required = [
      "parseRegistryMem",
      "parseRegistryPtr",
      "parseRegistryLst",
      "parseRegistryRtx",
      "resolveRegistry",
    ];
    for (const name of required) {
      if (typeof (mod as Record<string, unknown>)[name] !== "function") {
        return null;
      }
    }
    return mod as PortModule;
  } catch {
    return null;
  }
}

function decodeBase64(encoded: string): Uint8Array {
  return new Uint8Array(Buffer.from(encoded, "base64"));
}

function normalizeResolved(
  value: ResolvedSpan[] | Map<number, ResolvedSpan>,
): Map<number, ResolvedSpan> {
  if (value instanceof Map) return value;
  const out = new Map<number, ResolvedSpan>();
  for (const entry of value) out.set(entry.member_number, entry);
  return out;
}

const fixture: Fixture = JSON.parse(readFileSync(FIXTURE_PATH, "utf8"));

test("fixture declares the registry scope and six kinds", () => {
  assert.equal(fixture.schema, 1);
  assert.deepEqual(fixture.scope, ["registry"]);
  assert.equal(fixture.member_stride, 30);
  assert.equal(fixture.ptr_stride, 4);
  assert.equal(fixture.lst_stride, 8);
  assert.equal(fixture.trailer_struct, "<IB");
  assert.equal(fixture.span_struct, "<II");
  assert.equal(fixture.span_offset_in_member, 0x0a);
  assert.equal(fixture.trailer_size, 5);
  const kinds = fixture.kinds.map((k) => k.kind);
  assert.deepEqual(kinds, [
    "text",
    "image",
    "template",
    "concept",
    "tasklist",
    "Lexicon",
  ]);
  for (const k of fixture.kinds) {
    assert.equal(k.mem.byte_length % 30, 0, `${k.kind}.mem must be 30-aligned`);
    assert.equal(k.ptr.byte_length % 4, 0, `${k.kind}.ptr must be 4-aligned`);
    assert.equal(k.lst.byte_length % 8, 0, `${k.kind}.lst must be 8-aligned`);
    assert.equal(k.mem.record_count * 30, k.mem.byte_length);
    assert.equal(k.ptr.record_count * 4, k.ptr.byte_length);
    assert.equal(k.lst.record_count * 8, k.lst.byte_length);
    assert.equal(k.ptr.member_numbers.length, k.ptr.record_count);
    assert.equal(k.rtx.live_member_count, k.rtx.members.length);
  }
});

test("src/sm18-format-read.ts exports the five registry parsers", async (t) => {
  const port = await loadPort();
  if (port === null) {
    t.skip("registry parsers not implemented yet");
    return;
  }
  assert.equal(typeof port.parseRegistryMem, "function");
  assert.equal(typeof port.parseRegistryPtr, "function");
  assert.equal(typeof port.parseRegistryLst, "function");
  assert.equal(typeof port.parseRegistryRtx, "function");
  assert.equal(typeof port.resolveRegistry, "function");
});

for (const kind of fixture.kinds) {
  test(`format-read-registry: ${kind.kind}.mem decodes ${kind.mem.record_count} records`, async (t) => {
    const port = await loadPort();
    if (port === null) {
      t.skip("parseRegistryMem not implemented yet");
      return;
    }
    const bytes = decodeBase64(kind.mem.bytes_b64);
    assert.equal(bytes.byteLength, kind.mem.byte_length);
    const parsed = port.parseRegistryMem(bytes);
    assert.equal(parsed.length, kind.mem.record_count);
    for (let i = 0; i < kind.mem.record_count; i += 1) {
      assert.deepEqual(
        parsed[i],
        kind.mem.records[i],
        `${kind.kind}.mem record ${i} must match the fixture projection`,
      );
    }
  });

  test(`format-read-registry: ${kind.kind}.mem throws on partial trailing record`, async (t) => {
    const port = await loadPort();
    if (port === null) {
      t.skip("parseRegistryMem not implemented yet");
      return;
    }
    const bytes = decodeBase64(kind.mem.bytes_b64);
    const truncated = bytes.slice(0, bytes.byteLength - 1);
    assert.throws(
      () => port.parseRegistryMem(truncated),
      `${kind.kind}.mem truncated must throw`,
    );
  });

  test(`format-read-registry: ${kind.kind}.ptr decodes ${kind.ptr.record_count} member numbers`, async (t) => {
    const port = await loadPort();
    if (port === null) {
      t.skip("parseRegistryPtr not implemented yet");
      return;
    }
    const bytes = decodeBase64(kind.ptr.bytes_b64);
    assert.equal(bytes.byteLength, kind.ptr.byte_length);
    const parsed = port.parseRegistryPtr(bytes);
    assert.deepEqual(parsed, kind.ptr.member_numbers);
  });

  test(`format-read-registry: ${kind.kind}.ptr throws on partial trailing record`, async (t) => {
    const port = await loadPort();
    if (port === null) {
      t.skip("parseRegistryPtr not implemented yet");
      return;
    }
    const bytes = decodeBase64(kind.ptr.bytes_b64);
    const truncated = bytes.slice(0, bytes.byteLength - 1);
    assert.throws(
      () => port.parseRegistryPtr(truncated),
      `${kind.kind}.ptr truncated must throw`,
    );
  });

  test(`format-read-registry: ${kind.kind}.lst decodes ${kind.lst.record_count} records`, async (t) => {
    const port = await loadPort();
    if (port === null) {
      t.skip("parseRegistryLst not implemented yet");
      return;
    }
    const bytes = decodeBase64(kind.lst.bytes_b64);
    assert.equal(bytes.byteLength, kind.lst.byte_length);
    const parsed = port.parseRegistryLst(bytes);
    assert.equal(parsed.length, kind.lst.record_count);
    for (let i = 0; i < kind.lst.record_count; i += 1) {
      assert.deepEqual(
        parsed[i],
        kind.lst.records[i],
        `${kind.kind}.lst record ${i} must match the fixture projection`,
      );
    }
  });

  test(`format-read-registry: ${kind.kind}.rtx parses to ${kind.rtx.live_member_count} spans with matching geometry`, async (t) => {
    const port = await loadPort();
    if (port === null) {
      t.skip("parseRegistryRtx not implemented yet");
      return;
    }
    const bytes = decodeBase64(kind.rtx.redacted_bytes_b64);
    assert.equal(bytes.byteLength, kind.rtx.byte_length);
    const spans = port.parseRegistryRtx(bytes);
    const regularSpans = spans.filter(
      (s) => typeof s.member_number === "number" && s.member_number !== 0,
    );
    assert.equal(
      regularSpans.length,
      kind.rtx.live_member_count,
      `${kind.kind}.rtx live-member count must match the fixture`,
    );
    const spansByMember = new Map<number, RtxSpan>();
    for (const span of regularSpans) spansByMember.set(span.member_number, span);
    for (const pinned of kind.rtx.members) {
      const got = spansByMember.get(pinned.member_number);
      assert.ok(got, `${kind.kind}.rtx missing member ${pinned.member_number}`);
      assert.equal(
        got.span_offset,
        pinned.span_offset,
        `${kind.kind} member ${pinned.member_number} span_offset`,
      );
      assert.equal(
        got.span_length,
        pinned.span_length,
        `${kind.kind} member ${pinned.member_number} span_length`,
      );
      assert.equal(
        got.active,
        pinned.trailer_active,
        `${kind.kind} member ${pinned.member_number} active`,
      );
    }
  });

  test(`format-read-registry: resolveRegistry(${kind.kind}) returns ${kind.rtx.live_member_count} spans`, async (t) => {
    const port = await loadPort();
    if (port === null) {
      t.skip("resolveRegistry not implemented yet");
      return;
    }
    const resolved = normalizeResolved(
      port.resolveRegistry({
        mem: decodeBase64(kind.mem.bytes_b64),
        ptr: decodeBase64(kind.ptr.bytes_b64),
        rtx: decodeBase64(kind.rtx.redacted_bytes_b64),
      }),
    );
    assert.equal(
      resolved.size,
      kind.rtx.live_member_count,
      `${kind.kind} resolve live count`,
    );
    for (const pinned of kind.rtx.members) {
      const got = resolved.get(pinned.member_number);
      assert.ok(got, `${kind.kind} resolve missing ${pinned.member_number}`);
      assert.equal(got.span_offset, pinned.span_offset);
      assert.equal(got.span_length, pinned.span_length);
    }
  });
}
